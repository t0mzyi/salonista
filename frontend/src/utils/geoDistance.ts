/**
 * Finds lat/lng from any Kerala location text or district
 */
export function getCoordsFromLocationText(locationText?: string): { lat: number; lng: number } {
  if (!locationText) return { lat: 10.5276, lng: 76.2144 };
  const raw = locationText.toLowerCase();
  const parts = raw.split(',').map(p => p.trim()).filter(Boolean);

  // Check exact town matching first
  for (const part of parts) {
    if (KERALA_COORDINATES[part]) return KERALA_COORDINATES[part];
  }

  // Check substring in town list
  for (const [key, coords] of Object.entries(KERALA_COORDINATES)) {
    if (raw.includes(key)) return coords;
  }

  // Check district list
  for (const [dist, coords] of Object.entries(KERALA_DISTRICT_COORDINATES)) {
    if (raw.includes(dist)) return coords;
  }

  return { lat: 10.5276, lng: 76.2144 };
}

/**
 * Extracts EXACT coordinates from map_url or falls back to salon location text
 */
export function extractCoordsStrictlyFromMapUrl(mapUrl?: string, salonLocationText?: string): { lat: number; lng: number } {
  if (mapUrl) {
    // 1. Google Maps search path coordinates (e.g. /maps/search/10.508906,+76.057532 or /maps/search/10.508906,76.057532)
    const matchSearch = mapUrl.match(/\/maps\/search\/(-?\d+\.\d+)(?:,\+|\+|,|\s+)(-?\d+\.\d+)/);
    if (matchSearch) {
      return { lat: parseFloat(matchSearch[1]), lng: parseFloat(matchSearch[2]) };
    }

    // 2. Google Maps place data coordinates (!3dLAT!4dLNG) - Most accurate for specific businesses/pins
    const matchData = mapUrl.match(/!3d(-?\d+\.\d+)!4d(-?\d+\.\d+)/);
    if (matchData) {
      return { lat: parseFloat(matchData[1]), lng: parseFloat(matchData[2]) };
    }

    // 3. Query param coordinates (e.g. ?q=10.524933,76.047181 or &ll=10.524933,76.047181)
    const matchCoords = mapUrl.match(/[?&](?:q|ll|query|destination)=(-?\d+\.\d+)(?:,\+|\+|,|\s+)(-?\d+\.\d+)/);
    if (matchCoords) {
      return { lat: parseFloat(matchCoords[1]), lng: parseFloat(matchCoords[2]) };
    }

    // 4. Direct Lat/Lng in URL path (e.g. google.com/maps/@10.524933,76.047181,17z)
    const matchAt = mapUrl.match(/@(-?\d+\.\d+),(-?\d+\.\d+)/);
    if (matchAt) {
      return { lat: parseFloat(matchAt[1]), lng: parseFloat(matchAt[2]) };
    }

    // 5. Place search in map_url (e.g. maps.google.com/?q=Guruvayur)
    const matchQuery = mapUrl.match(/[?&]q=([^&]+)/);
    if (matchQuery) {
      const term = decodeURIComponent(matchQuery[1]).toLowerCase();
      for (const [key, coords] of Object.entries(KERALA_COORDINATES)) {
        if (term.includes(key)) return coords;
      }
    }
  }

  // Fallback to salon text location (e.g. "Thrissur", "Adimali", "Kochi") if map_url was a shortlink without coords
  if (salonLocationText) {
    return getCoordsFromLocationText(salonLocationText);
  }

  return { lat: 10.5276, lng: 76.2144 };
}

/**
 * Returns exact distance in kilometers using the Haversine formula
 */
export function getHaversineDistanceKm(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const R = 6371; // Earth radius in km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return +(R * c).toFixed(1);
}

/**
 * Calculates distance strictly between:
 *  1. The selected user area (e.g. "Adimali, Idukki" or "Chettuva, Thrissur")
 *  2. The salon's `map_url` coordinates, with smart fallback to salon text location
 */
export function calculateDistanceBetweenLocationAndMap(selectedUserLocation: string, salonMapUrl?: string, salonLocationText?: string): number {
  const userCoords = getCoordsFromLocationText(selectedUserLocation);

  // Extract coordinates from map_url (or salon location fallback if shortlink cannot be resolved locally)
  const salonMapCoords = extractCoordsStrictlyFromMapUrl(salonMapUrl, salonLocationText);

  return getHaversineDistanceKm(userCoords.lat, userCoords.lng, salonMapCoords.lat, salonMapCoords.lng);
}
